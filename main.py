
import streamlit as st
import pandas as pd
import plotly.express as px

# ---------------------------------
# 페이지 설정
# ---------------------------------
st.set_page_config(
    page_title="층간소음 발생 추이 분석",
    page_icon="🏠",
    layout="wide"
)

# ---------------------------------
# 사이트 소개
# ---------------------------------
st.title("🏠 층간소음 발생 추이 분석")

st.markdown("""
### 층간소음, 얼마나 자주 발생하고 있을까?

층간소음은 공동주택에서 위층이나 주변 세대의 생활 소리로 인해
다른 세대가 불편을 겪는 현상을 의미합니다.

뛰거나 걷는 소리, 가구를 끄는 소리, 망치질 등 다양한 원인으로
층간소음이 발생하며, 이는 이웃 간 갈등으로 이어지기도 합니다.

이 웹사이트는 **한국환경공단의 층간소음 원인별 분석 자료**를 활용하여
2012년부터 2024년까지 층간소음 발생 횟수가 어떻게 변화했는지
한눈에 확인할 수 있도록 제작되었습니다.
""")

st.divider()

# ---------------------------------
# 데이터
# ---------------------------------
data = {
    "연도": [
        2012, 2013, 2014, 2015, 2016, 2017, 2018,
        2019, 2020, 2021, 2022, 2023, 2024
    ],
    "발생 횟수": [
        1829, 3271, 4465, 4712, 6306, 9226, 10142,
        7971, 12139, 9211, 7771, 7064, 7033
    ]
}

df = pd.DataFrame(data)

# ---------------------------------
# 그래프
# ---------------------------------
st.subheader("📈 연도별 층간소음 발생 횟수")

st.write(
    "아래 그래프는 2012년부터 2024년까지의 "
    "연도별 층간소음 전체 발생 횟수를 나타냅니다."
)

fig = px.line(
    df,
    x="연도",
    y="발생 횟수",
    markers=True,
    text="발생 횟수",
    labels={
        "연도": "연도",
        "발생 횟수": "층간소음 발생 횟수(회)"
    }
)

fig.update_traces(
    line=dict(width=3),
    marker=dict(size=8),
    texttemplate="%{text:,}",
    textposition="top center"
)

fig.update_layout(
    xaxis=dict(
        tickmode="linear",
        dtick=1
    ),
    yaxis=dict(
        title="층간소음 발생 횟수(회)",
        rangemode="tozero"
    ),
    xaxis_title="연도",
    hovermode="x unified"
)

st.plotly_chart(
    fig,
    use_container_width=True
)

# ---------------------------------
# 그래프 해석 안내
# ---------------------------------
st.subheader("📌 그래프 살펴보기")

st.markdown("""
- **증가 추세:** 2012년부터 2018년까지 발생 횟수가 전반적으로 증가했습니다.
- **최고 발생 연도:** 2020년에 12,139회로 가장 많았습니다.
- **최근 변화:** 2020년 이후에는 전반적으로 감소했으며, 2024년에는 7,033회를 기록했습니다.

그래프를 통해 층간소음 발생 횟수가 매년 일정하게 변화하는 것이 아니라
연도에 따라 증가하거나 감소하는 모습을 확인할 수 있습니다.
""")

st.divider()

# ---------------------------------
# 자료 출처
# ---------------------------------
st.subheader("📚 자료 출처")

st.markdown("""
- 자료명: 한국환경공단 층간소음 원인별 분석
- 분석 기간: 2012년 ~ 2024년
- 자료 제공: 한국환경공단
- 자료 확인: [공공데이터포털](https://www.data.go.kr/data/15093156/fileData.do)
""")

st.caption(
    "본 웹사이트는 공공데이터를 활용하여 "
    "층간소음 발생 추이를 시각적으로 나타낸 자료 분석 사이트입니다."
)
